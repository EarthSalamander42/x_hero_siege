XHSBossTelegraphs.DEFAULT_PRIMARY = Vector(255, 110, 35)
XHSBossTelegraphs.DEFAULT_SECONDARY = Vector(120, 255, 80)

local function ValidVector(value)
	return value ~= nil and value.x ~= nil and value.y ~= nil and value.z ~= nil
end

local function ResolveParticle(colors, geometry)
	local family = colors and colors.family and XHSBossTelegraphs.PARTICLE_FAMILIES[colors.family]
	if family == nil then
		return XHSBossTelegraphs.PARTICLE, "xhs_generic"
	end
	return family[geometry] or family.circle or XHSBossTelegraphs.PARTICLE, family[geometry .. "_contract"] or family.contract
end

local function RegisterCircleDanger(position, radius, duration)
	if XHSBotDangerRegistry ~= nil and XHSBotDangerRegistry.AddCircle ~= nil then
		XHSBotDangerRegistry:AddCircle(position, radius or 180, duration or 1.0, {
			severity = 1,
			label = "phase3_boss_telegraph",
		})
	end
end

local function CreateWarning(position, radius, duration, colors, geometry, skipDangerRegistry)
	if not ValidVector(position) then return nil end
	colors = colors or {}
	local primary = colors.primary or XHSBossTelegraphs.DEFAULT_PRIMARY
	local secondary = colors.secondary or XHSBossTelegraphs.DEFAULT_SECONDARY
	local style = colors.style or 0

	-- The visual telegraph remains authoritative for players. In a Tools bot
	-- session, mirror it into the AI danger registry so bots react to the exact
	-- same warning window instead of reading hidden spell state.
	if skipDangerRegistry ~= true then RegisterCircleDanger(position, radius, duration) end

	local particlePath, contract = ResolveParticle(colors, geometry)
	local particle = ParticleManager:CreateParticle(particlePath, PATTACH_WORLDORIGIN, nil)
	ParticleManager:SetParticleControl(particle, 0, position)
	if contract == "aghanim_radius_time" then
		-- Aghanim telegraphs use CP1 = (world radius, lifetime, reserved),
		-- CP15 as the authored tint and CP16.x as tint influence.
		ParticleManager:SetParticleControl(particle, 1, Vector(radius or 180, duration or 1.0, 0))
		ParticleManager:SetParticleControl(particle, 15, primary)
		ParticleManager:SetParticleControl(particle, 16, Vector(1, 0, 0))
	else
		ParticleManager:SetParticleControl(particle, 1, Vector(radius or 180, 0, 0))
	end
	ParticleManager:SetParticleControl(particle, 2, Vector(duration or 1.0, 0, 0))
	ParticleManager:SetParticleControl(particle, 3, primary)
	ParticleManager:SetParticleControl(particle, 4, secondary)
	ParticleManager:SetParticleControl(particle, 5, Vector(style, 0, 0))
	Timers:CreateTimer(math.max(0.1, duration or 1.0) + 0.15, function()
		ParticleManager:DestroyParticle(particle, false)
		ParticleManager:ReleaseParticleIndex(particle)
		return nil
	end)
	return particle
end

local function CreateLineWarning(startPosition, endPosition, width, duration, colors)
	local particlePath, contract = ResolveParticle(colors, "line")
	if contract ~= "kez_line_duration_width" then return nil end

	colors = colors or {}
	local primary = colors.primary or XHSBossTelegraphs.DEFAULT_PRIMARY
	local secondary = colors.secondary or XHSBossTelegraphs.DEFAULT_SECONDARY
	local particle = ParticleManager:CreateParticle(particlePath, PATTACH_WORLDORIGIN, nil)
	ParticleManager:SetParticleControl(particle, 0, startPosition)
	ParticleManager:SetParticleControl(particle, 1, endPosition)
	ParticleManager:SetParticleControl(particle, 2, Vector(duration or 1.0, width or 180, 1))
	ParticleManager:SetParticleControl(particle, 15, primary)
	ParticleManager:SetParticleControl(particle, 16, secondary)
	Timers:CreateTimer(math.max(0.1, duration or 1.0) + 0.15, function()
		ParticleManager:DestroyParticle(particle, false)
		ParticleManager:ReleaseParticleIndex(particle)
		return nil
	end)
	return particle
end

function XHSBossTelegraphs:Circle(position, radius, duration, colors)
	return CreateWarning(position, radius, duration, colors, "circle")
end

function XHSBossTelegraphs:Target(position, radius, duration, colors)
	return CreateWarning(position, radius, duration, colors, "target")
end

-- Visual payoff only: CP0 is the cast origin and CP1.x is the final radius.
-- It deliberately does not register danger or own any gameplay timing.
function XHSBossTelegraphs:Release(position, radius, colors)
	if not ValidVector(position) then return nil end
	local particlePath, contract = ResolveParticle(colors or {}, "release")
	if contract ~= "release_radius" then return nil end
	local particle = ParticleManager:CreateParticle(particlePath, PATTACH_WORLDORIGIN, nil)
	ParticleManager:SetParticleControl(particle, 0, position)
	ParticleManager:SetParticleControl(particle, 1, Vector(radius or 180, 0, 0))
	Timers:CreateTimer(0.5, function()
		ParticleManager:DestroyParticle(particle, false)
		ParticleManager:ReleaseParticleIndex(particle)
	end)
	return particle
end

function XHSBossTelegraphs:Ring(center, ringRadius, nodeRadius, count, duration, colors, offsetDegrees)
	if not ValidVector(center) then return end

	count = math.max(1, count or 8)
	for i = 1, count do
		local angle = ((i - 1) / count) * 360 + (offsetDegrees or 0)
		local position = RotatePosition(center, QAngle(0, angle, 0), center + Vector(ringRadius or 500, 0, 0))
		CreateWarning(position, nodeRadius or 180, duration, colors, "ring")
	end
end

function XHSBossTelegraphs:Line(startPosition, direction, spacing, nodeRadius, count, duration, colors, startDistance)
	if not ValidVector(startPosition) or direction == nil then return end

	direction.z = 0
	if direction:Length2D() <= 0 then direction = Vector(1, 0, 0) end
	direction = direction:Normalized()
	count = math.max(1, count or 1)

	local positions = {}
	for i = 1, count do
		local position = startPosition + direction * ((startDistance or 0) + (spacing or 0) * (i - 1))
		positions[i] = position
		RegisterCircleDanger(position, nodeRadius or 180, duration)
	end

	if count > 1 and CreateLineWarning(positions[1], positions[count], nodeRadius, duration, colors) ~= nil then
		return
	end

	for _, position in ipairs(positions) do
		CreateWarning(position, nodeRadius or 180, duration, colors, "circle", true)
	end
end

